def source_fingerprint(text: str) -> str:
    """Return a short content hash of the Markdown source.

    A content hash (not a commit SHA) keeps the output deterministic: the HTML can
    be rebuilt in the same commit as the Markdown change, and --check still passes.
    """
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def render(source: Path, label: str) -> str:
    """Render one Markdown source to a self-contained HTML page."""
    text = source.read_text(encoding="utf-8")
    body_md = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    md = markdown.Markdown(
        extensions=["tables", "fenced_code", "toc", "sane_lists", "nl2br"],
        extension_configs={"toc": {"toc_depth": "2-2"}},
    )
    body = md.convert(body_md)
    body = body.replace("<table>", '<div class="tablewrap"><table>')
    body = body.replace("</table>", "</table></div>")
    title_match = re.search(r"^# (.+)$", body_md, re.M)
    title = title_match.group(1) if title_match else source.stem
    version = re.search(
        r"(?:\*\*Version:\*\*|Document set version:)\s*([^\s·]+)", body_md
    )
    dated = re.search(r"(?:\*\*Date:\*\*|Last updated:)\s*([0-9-]+)", body_md)
    sha = source_fingerprint(text)
    rel = source.relative_to(ROOT).as_posix()
    stamp = (
        f"Generated from <code>{html.escape(rel)}</code>"
        f" · version {html.escape(version.group(1)) if version else 'n/a'}"
        f" · dated {html.escape(dated.group(1)) if dated else 'n/a'}"
        f" · source fingerprint {sha}."
        " Do not edit this file; edit the Markdown in Git and rebuild."
    )
    toc = (
        f'<nav class="toc" aria-label="Contents">{md.toc}</nav>'
        if "<li>" in md.toc
        else ""
    )
    first_h2 = body.find("<h2")
    if first_h2 > 0 and toc:
        body = body[:first_h2] + toc + body[first_h2:]
    return (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        '<meta name="generator" content="build_guides.py; '
        f'source={html.escape(rel)}; fingerprint={sha}">'
        f"<title>{html.escape(label or title)}</title><style>{CSS}</style></head>"
        f'<body><main><div class="stamp">{stamp}</div>{body}'
        f"<footer>{stamp}</footer></main></body></html>\n"
    )


def main() -> int:
    """Parse command-line arguments and run this tool."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if any guide is stale"
    )
    args = parser.parse_args()
    entries = json.loads(MANIFEST.read_text(encoding="utf-8"))["guides"]
    stale = []
    for entry in entries:
        source, output = ROOT / entry["source"], ROOT / entry["output"]
        rendered = render(source, entry.get("label", ""))
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if rendered != current:
            stale.append(entry["output"])
            if not args.check:
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(rendered, encoding="utf-8")
    if args.check and stale:
        print("Stale guides (run scripts/build_guides.py):", *stale, sep="\n  ")
        return 1
    outcome = "stale" if args.check else "updated"
    print(f"{len(entries)} guides checked; {len(stale)} {outcome}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
