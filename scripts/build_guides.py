"""Build self-contained HTML guides from Markdown sources (docs-as-code projection).

Markdown in Git is the source of truth. This script renders each source listed in
docs/guides/guides.json to a single self-contained HTML file in docs/guides/ for
reading in Teams, SharePoint and Confluence. Never edit the HTML by hand.

Usage:
    uv run python scripts/build_guides.py # regenerate all guides
    uv run python scripts/build_guides.py --check # CI: fail if any guide is stale

The output is deterministic: the stamp uses the source's Version/Date lines and a
content fingerprint, not the build time, so --check only fails when content changed.
"""

